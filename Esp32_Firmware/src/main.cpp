// BLE SERVER CALLBACK
class ServerCallbacks : public NimBLEServerCallbacks {

  void onConnect(NimBLEServer* pServer, NimBLEConnInfo& connInfo) override {
    phoneConnected = true;
    Serial.println("Phone Connected");
  }

  void onDisconnect(
    NimBLEServer* pServer,
    NimBLEConnInfo& connInfo,
    int reason
  ) override {

    phoneConnected = false;
    // directionText = "--";
    directionText = "--";
distanceText = "--";
instructionText = "--";

    Serial.println("Phone Disconnected");

    NimBLEDevice::startAdvertising();
  }
};

// BLE DATA CALLBACK
class MyCallbacks : public NimBLECharacteristicCallbacks {

void onWrite(
  NimBLECharacteristic* pChar,
  NimBLEConnInfo& connInfo
) override {

  String data = String(pChar->getValue().c_str());

  Serial.println("RAW: " + data);

  int separator = data.indexOf('|');

  if (separator == -1) return;

  directionText = data.substring(0, separator);

  String payload = data.substring(separator + 1);

  // Extract distance (e.g. "195 m")
  int firstSpace = payload.indexOf(' ');
  int secondSpace = payload.indexOf(' ', firstSpace + 1);

  if (firstSpace != -1 && secondSpace != -1) {
    distanceText = payload.substring(0, secondSpace);
    instructionText = payload.substring(secondSpace + 1);
  } else {
    distanceText = "--";
    instructionText = payload;
  }

  // Clean text
  instructionText.replace("\n", " ");
  instructionText.replace("\r", " ");
  instructionText.trim();

  if (directionText == "") directionText = "--";
  if (distanceText == "") distanceText = "--";
  if (instructionText == "") instructionText = "--";

  // restart ticker from beginning
  scrollX = 0;
}
};

void setup() {
  Serial.begin(115200);

  Wire.begin(OLED_SDA, OLED_SCL);
  pinMode(BUTTON_PIN, INPUT_PULLUP);

  if (!display.begin(SSD1306_SWITCHCAPVCC, 0x3C)) {
    while (true); 
  }

  randomSeed(analogRead(0));

  // BLE INIT
  NimBLEDevice::init("BikeNav");
  NimBLEDevice::setMTU(247);

  NimBLEServer* server = NimBLEDevice::createServer();
  server->setCallbacks(new ServerCallbacks());

  NimBLEService* service = server->createService(SERVICE_UUID);

  NimBLECharacteristic* characteristic =
    service->createCharacteristic(
      CHARACTERISTIC_UUID,
      NIMBLE_PROPERTY::WRITE |
      NIMBLE_PROPERTY::WRITE_NR
    );

  characteristic->setCallbacks(new MyCallbacks());

  NimBLEAdvertising* advertising = NimBLEDevice::getAdvertising();
  advertising->addServiceUUID(SERVICE_UUID);
  advertising->start();

  Serial.println("BLE READY");

  showWelcomeScreen();
  // delay(2000);
}

void loop() {

  // BUTTON TOGGLE
  bool currentButtonState = digitalRead(BUTTON_PIN);

  if (lastButtonState == HIGH &&
      currentButtonState == LOW) {

    eyeMode = !eyeMode;
    delay(200);
  }

  lastButtonState = currentButtonState;

  // EYE MODE
  if (eyeMode) {

    if (millis() - lastMove > 700) {
      randomEyeMovement();
      lastMove = millis();
    }

    if (millis() - lastBlink > blinkInterval) {
      blinkEyes();
      blinkInterval = random(2000, 6000);
      lastBlink = millis();
    }

  } else {

    if (!phoneConnected) {
      showStartupScreen();
    } else {
      showNavScreen();
    }
  }
}